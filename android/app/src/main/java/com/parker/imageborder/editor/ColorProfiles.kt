package com.parker.imageborder.editor

import com.parker.imageborder.R

import android.graphics.ColorSpace
import java.nio.ByteBuffer
import java.nio.ByteOrder
import java.util.Calendar
import java.util.TimeZone
import kotlin.math.roundToInt

/** Matrix/TRC ICC v4 profile for the exact RGB space used by the rendered pixel buffer. */
object ColorProfiles {
    private fun buffer(n:Int)=ByteBuffer.allocate(n).order(ByteOrder.BIG_ENDIAN)
    private fun ByteBuffer.signature(s:String){put(s.toByteArray(Charsets.US_ASCII))}
    private fun ByteBuffer.fixed(x:Double){putInt((x*65536).roundToInt())}
    private fun xyz(v:FloatArray)=buffer(20).apply{signature("XYZ ");putInt(0);v.forEach{fixed(it.toDouble())}}.array()
    private fun description(text:String):ByteArray {
        val bytes=text.toByteArray(Charsets.UTF_16BE)
        return buffer(28+bytes.size).apply{signature("mluc");putInt(0);putInt(1);putInt(12);signature("enUS");putInt(bytes.size);putInt(28);put(bytes)}.array()
    }
    fun encode(space:ColorSpace.Rgb):ByteArray {
        val parameters=space.transferParameters?:error(appText(R.string.ui_cannot_encode_this_color_curve_as_icc_choose_srgb_b10036))
        val d50=floatArrayOf(.964212f,1f,.825188f)
        val adapted=ColorSpace.adapt(space,d50) as ColorSpace.Rgb
        val m=adapted.transform
        val curve=buffer(40).apply{signature("para");putInt(0);putShort(4);putShort(0)
            for(v in listOf(parameters.g,parameters.a,parameters.b,parameters.c,parameters.d,parameters.e,parameters.f))fixed(v)}.array()
        val adaptation=ColorSpace.chromaticAdaptation(ColorSpace.Adaptation.BRADFORD,space.whitePoint,d50)
        val tags=linkedMapOf("desc" to description(space.name),"cprt" to description("Colorimetric profile generated by Image Border"),"wtpt" to xyz(d50),
            "rXYZ" to xyz(floatArrayOf(m[0],m[1],m[2])),"gXYZ" to xyz(floatArrayOf(m[3],m[4],m[5])),"bXYZ" to xyz(floatArrayOf(m[6],m[7],m[8])),
            "rTRC" to curve,"gTRC" to curve,"bTRC" to curve,
            "chad" to buffer(44).apply{signature("sf32");putInt(0);for(row in 0..2)for(col in 0..2)fixed(adaptation[col*3+row].toDouble())}.array())
        var size=128+4+tags.size*12
        for(data in tags.values)size+=(data.size+3)/4*4
        return buffer(size).apply{
            putInt(size);signature("IB20");putInt(0x04300000);signature("mntr");signature("RGB ");signature("XYZ ")
            val now=Calendar.getInstance(TimeZone.getTimeZone("UTC"))
            for(value in listOf(now.get(Calendar.YEAR),now.get(Calendar.MONTH)+1,now.get(Calendar.DAY_OF_MONTH),now.get(Calendar.HOUR_OF_DAY),now.get(Calendar.MINUTE),now.get(Calendar.SECOND)))putShort(value.toShort())
            signature("acsp");putInt(0);putInt(0);putInt(0);putInt(0);putLong(0);putInt(0);d50.forEach{fixed(it.toDouble())};signature("IB20")
            position(128);putInt(tags.size);var offset=128+4+tags.size*12
            for((tag,data)in tags){signature(tag);putInt(offset);putInt(data.size);offset+=(data.size+3)/4*4}
            for(data in tags.values){put(data);while(position()%4!=0)put(0)}
        }.array()
    }
}
